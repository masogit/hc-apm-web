package com.ge.apm.service.asset;

import com.ge.apm.dao.DeptTransactionCategoryRepository;
import com.ge.apm.domain.DeptTransactionCategory;
import webapp.framework.web.WebUtil;

import javax.faces.component.UIComponent;
import javax.faces.context.FacesContext;
import javax.faces.convert.Converter;
import javax.faces.convert.FacesConverter;

@FacesConverter("transactionConverter")
public class TransactionConverter implements Converter {

    @Override
    public Object getAsObject(FacesContext fc, UIComponent uic, String value) {
        if (value != null && value.trim().length() > 0) {
            try {
                DeptTransactionCategoryRepository deptTransactionCategoryRepository = WebUtil.getBean(DeptTransactionCategoryRepository.class);

                return deptTransactionCategoryRepository.findById(Integer.valueOf(value));
            } catch (NumberFormatException e) {
                return null;
            }
        } else {
            return null;
        }
    }

    @Override
    public String getAsString(FacesContext fc, UIComponent uic, Object object) {
        if(object != null) {
            return String.valueOf(((DeptTransactionCategory) object).getId());
        }
        else {
            return null;
        }
    }

}
