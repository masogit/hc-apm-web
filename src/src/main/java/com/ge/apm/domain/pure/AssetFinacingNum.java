package com.ge.apm.domain.pure;

public class AssetFinacingNum {
	private Integer assetId;
	private String nationalStardCode;
	private String uid;
	private Integer majorAssetId;
	private String prefix;
	
	public Integer getAssetId() {
		return assetId;
	}
	public void setAssetId(Integer assetId) {
		this.assetId = assetId;
	}
	public String getNationalStardCode() {
		return nationalStardCode;
	}
	public void setNationalStardCode(String nationalStardCode) {
		this.nationalStardCode = nationalStardCode;
	}
	public String getUid() {
		return uid;
	}
	public void setUid(String uid) {
		this.uid = uid;
	}
	public Integer getMajorAssetId() {
		return majorAssetId;
	}
	public void setMajorAssetId(Integer majorAssetId) {
		this.majorAssetId = majorAssetId;
	}
	public String getPrefix() {
		return prefix;
	}
	public void setPrefix(String prefix) {
		this.prefix = prefix;
	}
	
	

}
